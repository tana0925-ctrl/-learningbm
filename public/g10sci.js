/* ============================================================
   高1理科基礎 単元パック v181（隠し高校エリア）
   物理基礎 / 化学基礎 / 生物基礎
   基礎40%・標準40%・発展20% 混合ランダム（4択・計算は自己完結）
   ============================================================ */
(function () {
  var G10 = window.G10; if (!G10) return;
  var R = G10.R, pick = G10.pick, Q = G10.q;

  // ① 物理基礎（等加速度運動・力と運動・エネルギー）
  function genButsuri10() {
    var r = R(1, 10), t;
    if (r <= 4) {
      t = R(0, 3);
      if (t === 0) return Q('基礎', '速さが一定の割合で増える運動を何という？', '等加速度直線運動', ['等速直線運動', '自由落下', '円運動']);
      if (t === 1) return Q('基礎', '加速度の単位はどれ？', 'm/s²', ['m/s', 'N', 'J']);
      if (t === 2) return Q('基礎', '「物体は外から力を受けなければ、静止または等速直線運動を続ける」という法則は？', '慣性の法則（運動の第1法則）', ['作用反作用の法則', '万有引力の法則', 'フックの法則']);
      return Q('基礎', '仕事や熱、エネルギーの単位はどれ？', 'J（ジュール）', ['N（ニュートン）', 'W（ワット）', 'Pa（パスカル）']);
    }
    if (r <= 8) {
      t = R(0, 2);
      if (t === 0) { var a = pick([2, 3, 4, 5]), tt = pick([2, 3, 4, 5]);
        // v = a t （初速0）
        return Q('標準', '初速度0、加速度 ' + a + 'm/s² で ' + tt + '秒後の速さは？（v = at）', (a * tt) + 'm/s', [(a + tt) + 'm/s', (a * tt * 2) + 'm/s', (a) + 'm/s']); }
      if (t === 1) return Q('標準', '運動の第2法則で、力 F・質量 m・加速度 a の関係は？', 'F = ma', ['F = m/a', 'F = a/m', 'F = m+a']);
      return Q('標準', '一方の物体が他方に力を加えると、同じ大きさで逆向きの力を受ける。この法則は？', '作用反作用の法則', ['慣性の法則', '運動量保存の法則', 'エネルギー保存の法則']);
    }
    t = R(0, 1);
    if (t === 0) { var m = pick([2, 3, 5]), aa = pick([2, 3, 4]);
      return Q('発展', '質量 ' + m + 'kg の物体に ' + (m * aa) + 'N の力を加えたときの加速度は？（a = F/m）', aa + 'm/s²', [(m * aa) + 'm/s²', (aa + 1) + 'm/s²', (m) + 'm/s²']); }
    var hh = pick([5, 10, 20]);
    // 位置エネルギー U=mgh, m=2kg, g=9.8 → 使わず概念問題に
    return Q('発展', '摩擦や空気抵抗を無視すると、運動エネルギーと位置エネルギーの和（力学的エネルギー）はどうなる？', '一定に保たれる（保存される）', ['増え続ける', '減り続ける', 'ゼロになる']);
  }

  // ② 化学基礎（原子構造・物質量mol・酸化還元）
  function genKagaku10() {
    var r = R(1, 10), t;
    if (r <= 4) {
      t = R(0, 3);
      if (t === 0) return Q('基礎', '原子の中心にあり、＋の電気をもつものは？', '原子核', ['電子', '中性子だけ', '分子']);
      if (t === 1) return Q('基礎', '原子核のまわりを回り、−の電気をもつ粒子は？', '電子', ['陽子', '中性子', 'イオン']);
      if (t === 2) return Q('基礎', '物質量（mol）で、1molあたりの粒子の数（アボガドロ定数）はおよそいくつ？', '6.0×10²³個', ['6.0×10²²個', '3.0×10²³個', '1.0×10²³個']);
      return Q('基礎', '物質が酸素と結びつく反応を何という？', '酸化', ['還元', '中和', '蒸留']);
    }
    if (r <= 8) {
      t = R(0, 3);
      if (t === 0) return Q('標準', '原子番号は、原子の何の数と等しい？', '陽子の数', ['中性子の数', '電子と中性子の合計', '質量数']);
      if (t === 1) return Q('標準', '質量数は、何と何の数の合計？', '陽子の数と中性子の数', ['陽子の数と電子の数', '電子の数と中性子の数', '陽子の数だけ']);
      if (t === 2) { var m = pick([2, 3, 4, 5]);
        // 水 H2O 18g/mol。m mol の質量
        return Q('標準', '水（H₂O、モル質量18g/mol）が ' + m + 'mol あるとき、質量は何g？（質量＝mol×モル質量）', (m * 18) + 'g', [(m + 18) + 'g', (m * 2) + 'g', (18) + 'g']); }
      return Q('標準', '物質が酸素を失う（または水素と結びつく）反応を何という？', '還元', ['酸化', '燃焼', '中和']);
    }
    t = R(0, 2);
    if (t === 0) return Q('発展', '酸化還元反応で、相手を酸化して自分は還元される物質を何という？', '酸化剤', ['還元剤', '触媒', '溶媒']);
    if (t === 1) return Q('発展', '炭素12g（1mol）に含まれる原子の数は、およそいくつ？', '6.0×10²³個', ['1.2×10²⁴個', '3.0×10²³個', '12個']);
    return Q('発展', '「酸化」を電子の授受で説明すると、原子や物質はどうなること？', '電子を失うこと', ['電子を受け取ること', '陽子を失うこと', '中性子を得ること']);
  }

  // ③ 生物基礎（細胞・代謝・遺伝子）
  function genSeibutsu10() {
    var r = R(1, 10), t;
    if (r <= 4) {
      t = R(0, 3);
      if (t === 0) return Q('基礎', '植物の細胞にはあって、動物の細胞にはないつくりはどれ？', '細胞壁', ['細胞膜', '核', 'ミトコンドリア']);
      if (t === 1) return Q('基礎', '細胞の呼吸を行い、エネルギーをとり出す細胞小器官はどれ？', 'ミトコンドリア', ['葉緑体', '核', '液胞']);
      if (t === 2) return Q('基礎', '光合成を行う、植物細胞の緑色の細胞小器官はどれ？', '葉緑体', ['ミトコンドリア', '核', '細胞壁']);
      return Q('基礎', '遺伝子の本体である物質は何？', 'DNA', ['タンパク質', 'ATP', 'ブドウ糖']);
    }
    if (r <= 8) {
      t = R(0, 3);
      if (t === 0) return Q('標準', '生体内でエネルギーの受け渡しに使われる物質（エネルギーの通貨）はどれ？', 'ATP', ['DNA', 'RNA', 'デンプン']);
      if (t === 1) return Q('標準', '生体内で起こる化学反応をまとめて何という？', '代謝', ['蒸散', '発生', '免疫']);
      if (t === 2) return Q('標準', '光合成でエネルギーをたくわえる反応（同化）に対し、呼吸のように分解してエネルギーを取り出す反応を何という？', '異化', ['同化', '受精', '分裂']);
      return Q('標準', 'DNA の情報をもとにつくられ、生命活動の中心的な役割を果たす物質はどれ？', 'タンパク質', ['脂質', 'デンプン', '水']);
    }
    t = R(0, 2);
    if (t === 0) return Q('発展', 'DNA を構成する4種類の塩基は、A・T・G と、あと1つはどれ？', 'C（シトシン）', ['U（ウラシル）', 'B', 'X']);
    if (t === 1) return Q('発展', 'DNA の二重らせん構造で、A（アデニン）と対になる塩基はどれ？', 'T（チミン）', ['G（グアニン）', 'C（シトシン）', 'A（アデニン）']);
    return Q('発展', '光合成を行う細胞小器官と、呼吸を行う細胞小器官の正しい組み合わせは？', '葉緑体と、ミトコンドリア', ['ミトコンドリアと、核', '核と、葉緑体', '細胞壁と、液胞']);
  }

  try {
    window.genButsuri10 = genButsuri10;
    window.genKagaku10 = genKagaku10;
    window.genSeibutsu10 = genSeibutsu10;
  } catch (e) {}

  G10.stage('science', [
    { id: 'r10-butsuri', name: '物理基礎', icon: '🔩', color: 'orange', gen: 'genButsuri10', input: 'mcq', desc: '等加速度運動・力と運動・エネルギー' },
    { id: 'r10-kagaku', name: '化学基礎', icon: '🎇', color: 'yellow', gen: 'genKagaku10', input: 'mcq', desc: '原子構造・物質量mol・酸化還元' },
    { id: 'r10-seibutsu', name: '生物基礎', icon: '🩻', color: 'green', gen: 'genSeibutsu10', input: 'mcq', desc: '細胞・代謝・遺伝子' }
  ], {
    'r10-butsuri': { name: '物理基礎の実験場', emoji: '🔩', desc: '物理基礎（高1理科）' },
    'r10-kagaku': { name: '化学基礎の反応室', emoji: '🎇', desc: '化学基礎（高1理科）' },
    'r10-seibutsu': { name: '生物基礎の細胞園', emoji: '🩻', desc: '生物基礎（高1理科）' }
  });
})();
