  // ---------------- 確率 ----------------
  function genKakuritsu8() {
    var r = R(1, 10), t, a, b, n, m;
    if (r <= 4) { // 基礎
      t = R(0, 4);
      if (t === 0) {
        var target = R(1, 6);
        return Q('基礎', '1個のさいころを1回投げるとき、' + target + 'の目が出る確率は？',
          '1/6', ['1/3', '1/2', '1/36']);
      }
      if (t === 1) {
        return Q('基礎', '1個のさいころを1回投げるとき、偶数の目が出る確率は？',
          '1/2', ['1/3', '1/6', '2/3']);
      }
      if (t === 2) {
        a = R(2, 6); b = R(2, 6);
        return Q('基礎', '赤玉 ' + a + '個と白玉 ' + b + '個が入った袋から1個取り出すとき、赤玉が出る確率は？',
          frac(a, a + b), [frac(b, a + b), frac(a, b), frac(1, a)]);
      }
      if (t === 3) {
        return Q('基礎', '1枚の硬貨を1回投げるとき、表が出る確率は？', '1/2', ['1/4', '1/3', '1']);
      }
      return Q('基礎', 'あることがらが必ず起こるとき、その確率はいくつ？', '1', ['0', '0.5', '100']);
    }
    if (r <= 8) { // 標準
      t = R(0, 4);
      if (t === 0) {
        return Q('標準', '2枚の硬貨を同時に投げるとき、2枚とも表になる確率は？',
          '1/4', ['1/2', '1/3', '3/4']);
      }
      if (t === 1) {
        return Q('標準', '2個のさいころを同時に投げるとき、出る目の和が7になる確率は？',
          '1/6', ['1/12', '7/36', '1/36']);
      }
      if (t === 2) {
        return Q('標準', '2個のさいころを同時に投げるとき、目の出方は全部で何通り？',
          '36通り', ['12通り', '6通り', '21通り']);
      }
      if (t === 3) {
        return Q('標準', '2個のさいころを同時に投げるとき、2つとも同じ目になる確率は？',
          '1/6', ['1/36', '1/12', '1/3']);
      }
      var mul = pick([3, 4]);
      var cnt = (mul === 3) ? 2 : 1; // 6以下で3の倍数は3,6の2個／4の倍数は4の1個
      return Q('標準', '1個のさいころを1回投げるとき、' + mul + 'の倍数の目が出る確率は？',
        frac(cnt, 6), [frac(6 - cnt, 6), frac(cnt, 36), frac(1, mul)]);
    }
    // 発展
    t = R(0, 3);
    if (t === 0) {
      return Q('発展', '2枚の硬貨を同時に投げるとき、少なくとも1枚が表になる確率は？',
        '3/4', ['1/2', '1/4', '2/3']);
    }
    if (t === 1) {
      return Q('発展', '3枚の硬貨を同時に投げるとき、3枚とも裏になる確率は？',
        '1/8', ['1/6', '1/4', '3/8']);
    }
    if (t === 2) {
      a = R(2, 4); b = R(2, 5);
      while (b === a) b = R(2, 5);
      var tot = a + b;
      // 玉を2個続けて取り出す（もどさない）で2個とも赤
      var pn = a * (a - 1), pd = tot * (tot - 1);
      return Q('発展', '赤玉 ' + a + '個、白玉 ' + b + '個の袋から続けて2個取り出す（もどさない）とき、\n2個とも赤玉になる確率は？',
        frac(pn, pd), [frac(a * a, tot * tot), frac(a, tot), frac(a * (a - 1), tot * tot)]);
    }
    return Q('発展', 'A、B、C の3人が1列に並ぶとき、並び方は全部で何通り？',
      '6通り', ['3通り', '9通り', '12通り']);
  }

