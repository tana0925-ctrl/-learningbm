MIN_ADD = 30
EXPECT_ADD = 34
EXPECT_FIX = 10


def die(msg):
    sys.stderr.write('FAIL: %s\n' % msg)
    sys.exit(1)


def js(o):
    return json.dumps(o, ensure_ascii=False)


def chain_count(s):
    i = s.index(ROOT_ANCHOR)
    j = s.index(END_ANCHOR, i)
    return s[i:j].count('.replace(')


def build_payload():
    # ES5 のみ。$ とテンプレートリテラルは使わない。
    parts = []
    parts.append(';(function(){try{')
    parts.append("if(typeof _H6ADD==='undefined'||typeof _H6NK!=='function'){return;}")
    parts.append("var K='h6u11';")
    parts.append('var _H6U11FIX_V1=' + js(FIX) + ';')
    parts.append('var _H6U11ADD_V1=' + js(ADD) + ';')
    parts.append('var mp={},i,j;')
    parts.append('for(i=0;i<_H6U11FIX_V1.length;i++){mp[_H6NK(_H6U11FIX_V1[i][0])]=_H6U11FIX_V1[i];}')
    parts.append('var pools=[];')
    parts.append("if(typeof _SS!=='undefined'&&_SS&&_SS[K]){pools.push(_SS[K]);}")
    parts.append("if(typeof _SC!=='undefined'&&_SC&&_SC[K]){pools.push(_SC[K]);}")
    parts.append('for(i=0;i<pools.length;i++){var arr=pools[i];'
                 'for(j=0;j<arr.length;j++){var f=mp[_H6NK(arr[j].q)];'
                 'if(f){if(f[1]){arr[j].correct=f[1];}arr[j].wrongs=f[2].slice();}}}')
    parts.append('_H6ADD[K]=(_H6ADD[K]||[]).concat(_H6U11ADD_V1);')
    parts.append("if(typeof _H6CACHE!=='undefined'&&_H6CACHE){delete _H6CACHE[K];}")
    parts.append('}catch(e){}})();')
    return ''.join(parts)


def self_check():
    if len(ADD) < MIN_ADD:
        die('追加問題が足りない: %d < %d' % (len(ADD), MIN_ADD))
    if len(ADD) != EXPECT_ADD:
        die('追加問題数が想定と違う: %d != %d' % (len(ADD), EXPECT_ADD))
    if len(FIX) != EXPECT_FIX:
        die('差し替え数が想定と違う: %d != %d' % (len(FIX), EXPECT_FIX))

    seen = {}
    for a in ADD:
        if not a['q'] or not a['correct']:
            die('空の問題がある')
        if len(a['wrongs']) != 3:
            die('誤答が3つでない: %r' % a['q'])
        opts = [a['correct']] + a['wrongs']
        if len(set(opts)) != 4:
            die('選択肢が重複している: %r' % a['q'])
        if a['q'] in seen:
            die('追加分の中で問題文が重複: %r' % a['q'])
        seen[a['q']] = 1

    fseen = {}
    for f in FIX:
        if len(f) != 3 or len(f[2]) != 3:
            die('差し替えの形が違う: %r' % (f[0],))
        if len(set(f[2])) != 3:
            die('差し替えの誤答が重複: %r' % (f[0],))
        if f[0] in fseen:
            die('差し替えキーが重複: %r' % (f[0],))
        fseen[f[0]] = 1


def main():
    self_check()

    with open(SRC, encoding='utf-8') as fp:
        s = fp.read()

    if SENTINEL in s:
        print('SKIP: 番兵 %s があるので何もしない' % SENTINEL)
        return

    # --- fail-closed: 前提の確認 ---------------------------------------
    if s.count(ROOT_ANCHOR) != 1:
        die('ルートのアンカーが一意でない: %d件' % s.count(ROOT_ANCHOR))
    if s.count(ANCHOR) != 1:
        die('genH6u11 のアンカーが一意でない: %d件' % s.count(ANCHOR))
    if s.count(INSERT_AT) != 1:
        die('挿入位置が一意でない: %d件' % s.count(INSERT_AT))
    for k in KEEP:
        if k not in s:
            die('既存の目印が消えている: %s' % k)

    n0 = chain_count(s)
    if n0 != CHAIN_BEFORE:
        die('チェーンが %d件（想定 %d件）' % (n0, CHAIN_BEFORE))

    payload = build_payload()
    if '$' in payload:
        die('payload に $ が含まれる（String.replace の置換指定と衝突する）')
    if '</' in payload:
        die('payload に </ が含まれる')

    new_line = (
        '\n      // ' + SENTINEL + ' : u11（新しい日本へ）追加' + str(len(ADD))
        + '問 + 誤答差し替え' + str(len(FIX)) + '問\n'
        '      t = t.replace(' + js(ANCHOR) + ', ' + js(ANCHOR + payload) + ')\n'
    )

    s2 = s.replace(INSERT_AT, new_line + INSERT_AT, 1)
    if s2 == s:
        die('挿入に失敗した')

    n1 = chain_count(s2)
    if n1 != CHAIN_AFTER:
        die('挿入後のチェーンが %d件（想定 %d件）' % (n1, CHAIN_AFTER))
    if s2.count(ANCHOR) != 3:
        die('挿入後の genH6u11 アンカーが %d件（想定 3件）' % s2.count(ANCHOR))
    if s2.count('wrongs') - s.count('wrongs') != payload.count('wrongs'):
        die('wrongs の増分が %d（想定 %d）'
            % (s2.count('wrongs') - s.count('wrongs'), payload.count('wrongs')))
    for tok in ('_H6U11ADD_V1', '_H6U11FIX_V1'):
        want = payload.count(tok)
        if want < 2:
            die('%s が payload に足りない' % tok)
        if s2.count(tok) != want:
            die('%s が %d件（想定 %d件）' % (tok, s2.count(tok), want))
    for k in KEEP:
        if s2.count(k) != s.count(k):
            die('既存の目印の数が変わった: %s' % k)

    with open(SRC, 'w', encoding='utf-8') as fp:
        fp.write(s2)

    print('OK: chain %d -> %d / 追加 %d問 / 誤答差し替え %d問'
          % (n0, n1, len(ADD), len(FIX)))


if __name__ == '__main__':
    main()
