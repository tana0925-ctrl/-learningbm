    tsx,
    'H.push(\'<div style="text-align:center"><div style="font-size:11px;font-weight:700;color:#475569;margin-bottom:2px">きもちの割合</div>\'+_kDonut(ov.sunCount,ov.cloudCount,ov.rainCount)+\'</div>\');',
    "/* KARTE_WEEKLY_V1 きもちの割合（ドーナツ）を外した。年度累計なので週では動かない"
    "（児童Aで5週 89%→83%）。満足度は先生の個人分析カードに出ている。 */",
