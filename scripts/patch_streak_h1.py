#!/usr/bin/env python3
# -*- coding: utf-8 -*-
#
# 連続日数の直し 第1便：祝日表を2028年3月末まで延ばすだけ
#
# さわるのは src/index.tsx の KHT_HOLIDAYS の1行だけ。
# 追加する日付はすべて 2026-11-23 より後なので、
# いま画面に出ている連続日数はどの子も1日も変わらない。
# （配信のしくみが動くことを、数字を動かさずに確かめるための便）
#
# 出典：国立天文台 暦要項
#   2027年 … 令和9年(2027)暦要項（令和8年2月2日発表）。3月22日は振替休日。
#   2028年1〜3月 … 暦要項が未発表。法律で日付が決まっているものだけ入れた。
#                   2028-03-20（春分の日）は天文計算による見込み。
#                   正式決定は2027年2月の暦要項。
#
# 表の終わりは KHT_HOLIDAYS_UNTIL に持たせる。
# ここを過ぎたら教師画面で知らせる（第2便でつける）。
# 学校独自の休み（開校記念日・振替休業など）はここには入れない。
# それは各クラスの extraHolidays に先生が足す（今は空のまま）。

import sys

PATH = 'src/index.tsx'

OLD = (
    "const KHT_HOLIDAYS = ['2026-01-01','2026-01-12','2026-02-11','2026-02-23',"
    "'2026-03-20','2026-04-29','2026-05-03','2026-05-04','2026-05-05','2026-05-06',"
    "'2026-07-20','2026-08-11','2026-09-21','2026-09-22','2026-09-23','2026-10-12',"
    "'2026-11-03','2026-11-23']"
)

NEW = (
    "const KHT_HOLIDAYS = ['2026-01-01','2026-01-12','2026-02-11','2026-02-23',"
    "'2026-03-20','2026-04-29','2026-05-03','2026-05-04','2026-05-05','2026-05-06',"
    "'2026-07-20','2026-08-11','2026-09-21','2026-09-22','2026-09-23','2026-10-12',"
    "'2026-11-03','2026-11-23',"
    "'2027-01-01','2027-01-11','2027-02-11','2027-02-23','2027-03-21','2027-03-22',"
    "'2027-04-29','2027-05-03','2027-05-04','2027-05-05','2027-07-19','2027-08-11',"
    "'2027-09-20','2027-09-23','2027-10-11','2027-11-03','2027-11-23',"
    "'2028-01-01','2028-01-10','2028-02-11','2028-02-23','2028-03-20']\n"
    "// 祝日表はここまで。これより後の日付は「祝日ではない」と見なされる。\n"
    "// 切れたことに気づけるよう、教師画面で知らせる（第2便）。\n"
    "const KHT_HOLIDAYS_UNTIL = '2028-03-31'"
)

ADDED = [
    '2027-01-01', '2027-01-11', '2027-02-11', '2027-02-23', '2027-03-21',
    '2027-03-22', '2027-04-29', '2027-05-03', '2027-05-04', '2027-05-05',
    '2027-07-19', '2027-08-11', '2027-09-20', '2027-09-23', '2027-10-11',
    '2027-11-03', '2027-11-23',
    '2028-01-01', '2028-01-10', '2028-02-11', '2028-02-23', '2028-03-20',
]

CHAIN_BEFORE = 158


def die(msg):
    print('### 中止: ' + msg)
    sys.exit(1)


def chain_count(src):
    a = src.index("app.get('/'")
    b = src.index("app.get('/logout'")
    if b <= a:
        die('チェーンの範囲が取れない（/ と /logout の順番がおかしい）')
    return src.count('.replace(', a, b)


def main():
    with open(PATH, encoding='utf-8') as f:
        src = f.read()

    before = chain_count(src)
    print('チェーン数（前）:', before)
    if before != CHAIN_BEFORE:
        die('チェーン数が %d（%d のはず）。ほかの便とぶつかっている可能性がある。' % (before, CHAIN_BEFORE))

    n = src.count(OLD)
    if n != 1:
        die('KHT_HOLIDAYS のあて先が %d 件（1件のはず）' % n)

    if 'KHT_HOLIDAYS_UNTIL' in src:
        die('KHT_HOLIDAYS_UNTIL がすでにある（この便はもう当たっている）')

    out = src.replace(OLD, NEW, 1)

    after = chain_count(out)
    print('チェーン数（後）:', after)
    if after != before:
        die('チェーン数が %d -> %d に変わった' % (before, after))

    missing = [d for d in ADDED if ("'" + d + "'") not in out]
    if missing:
        die('入らなかった日付がある: ' + ', '.join(missing))

    for d in ['2026-09-21', '2026-09-22', '2026-09-23', '2026-11-23']:
        if ("'" + d + "'") not in out:
            die('もとからあった日付が消えた: ' + d)

    for k in ['KHT_PRICE_STREAK = 500', 'KHT_PRICE_MID = 1500',
              'KHT_PRICE_NONE = 3000', 'KHT_STREAK_NEED = 3',
              'function khtStreak(', 'function khtIsRest(']:
        if src.count(k) != out.count(k):
            die('カフート券のところが変わってしまった: ' + k)

    d_lines = out.count('\n') - src.count('\n')
    if d_lines != 3:
        die('増えた行数が %d（3のはず）' % d_lines)

    with open(PATH, 'w', encoding='utf-8', newline='') as f:
        f.write(out)

    print('OK: 祝日を %d 日ぶん追加した（2027年度末まで）' % len(ADDED))
    print('OK: 有効期限 KHT_HOLIDAYS_UNTIL = 2028-03-31')
    print('OK: 2026年9月時点の連続日数は変わらない（追加はすべて 2026-11-23 より後）')


if __name__ == '__main__':
    main()
